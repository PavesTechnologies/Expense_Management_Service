package com.expense_management_service.entity;

import jakarta.persistence.*;
import lombok.*;

import java.math.BigDecimal;
import java.time.LocalDateTime;
import java.util.UUID;

/**
 * Finance's request to recover part of a cash advance through payroll, and the Payroll result once it is recorded.
 *
 * <p>Status is the request lifecycle only. The advance settlement status is separate: a confirmed request with a
 * remaining balance leaves the advance open. Only the actual amount deducted, recorded through
 * {@code CashAdvancePayrollPosting}, changes the advance balance.
 */
@Entity
@Table(name = "salary_deduction_request")
@Getter
@Setter
@NoArgsConstructor
@AllArgsConstructor
@Builder
public class SalaryDeductionRequest {

    /** Saved, email queued but not yet delivered to Payroll. */
    public static final String PENDING_SEND = "PENDING_SEND";
    /** The email to Payroll was delivered. Payroll has not reported a result yet. */
    public static final String SENT_TO_PAYROLL = "SENT_TO_PAYROLL";
    /** Payroll's result is recorded and the actual amount is posted (may be partial). */
    public static final String PAYROLL_CONFIRMED = "PAYROLL_CONFIRMED";
    /** Payroll's result is recorded as nothing deducted. The balance is unchanged. */
    public static final String PAYROLL_FAILED = "PAYROLL_FAILED";
    /** Cancelled by Finance. See {@link #sentToPayroll} for whether Payroll may already have acted on it. */
    public static final String CANCELLED = "CANCELLED";

    @Id
    @GeneratedValue(strategy = GenerationType.UUID)
    @Column(name = "salary_deduction_request_id", updatable = false, nullable = false)
    private UUID salaryDeductionRequestId;

    @Version
    @Column(name = "version", nullable = false)
    private Long version;

    /** Human-readable tracking ID, for example PR-2026-2027-1A2B3C4D. Not an authorization ID. */
    @Column(name = "payroll_request_id", nullable = false, unique = true, length = 32)
    private String payrollRequestId;

    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "advance_id", nullable = false)
    private CashAdvance advance;

    @Column(name = "employee_id", nullable = false, length = 255)
    private String employeeId;

    @Column(name = "requested_amount", nullable = false, precision = 19, scale = 4)
    private BigDecimal requestedAmount;

    /** Target payroll month, yyyy-MM. */
    @Column(name = "payroll_month", nullable = false, length = 7)
    private String payrollMonth;

    @Column(name = "status", nullable = false, length = 32)
    private String status;

    @Column(name = "requested_by", nullable = false, length = 255)
    private String requestedBy;

    @Column(name = "requested_at", nullable = false)
    private LocalDateTime requestedAt;

    /** The outbox row carrying the latest request email. Used to show delivery state and to dedupe retries. */
    @Column(name = "outbound_email_id")
    private UUID outboundEmailId;

    @Column(name = "sent_at")
    private LocalDateTime sentAt;

    /** True once the request email was delivered, even if the request was cancelled afterwards. */
    @Column(name = "sent_to_payroll", nullable = false)
    private boolean sentToPayroll;

    @Column(name = "cancelled_at")
    private LocalDateTime cancelledAt;

    @Column(name = "cancelled_by", length = 255)
    private String cancelledBy;

    @Column(name = "cancellation_reason", length = 500)
    private String cancellationReason;

    /** Set once Payroll's result is recorded, including a zero result. Blocks a second recording. */
    @Column(name = "outcome_recorded", nullable = false)
    private boolean outcomeRecorded;

    @Column(name = "actual_amount_deducted", precision = 19, scale = 4)
    private BigDecimal actualAmountDeducted;

    @Column(name = "payroll_month_processed", length = 7)
    private String payrollMonthProcessed;

    /** Payroll's own confirmation reference. Optional. Never generated by the system. */
    @Column(name = "payroll_reference", length = 100)
    private String payrollReference;

    /** Evidence type when there is no reference: PAYROLL_EMAIL, PAYSLIP, PAYROLL_RECORD or OTHER. */
    @Column(name = "evidence_type", length = 32)
    private String evidenceType;

    @Column(name = "evidence_reference", length = 512)
    private String evidenceReference;

    @Column(name = "evidence_note", length = 500)
    private String evidenceNote;

    @Column(name = "confirmed_at")
    private LocalDateTime confirmedAt;

    @Column(name = "confirmed_by", length = 255)
    private String confirmedBy;

    /** The automated recovery case this request was raised for, when it was created by the due-date run. */
    @Column(name = "recovery_case_id")
    private UUID recoveryCaseId;

    /**
     * A request is open while Payroll may still act on it: not yet sent, sent and awaiting a result, or cancelled
     * after it reached Payroll without a recorded result. An open request blocks a new one for the same advance.
     */
    public boolean isOpen() {
        return PENDING_SEND.equals(status)
                || SENT_TO_PAYROLL.equals(status)
                || (CANCELLED.equals(status) && sentToPayroll && !outcomeRecorded);
    }
}
